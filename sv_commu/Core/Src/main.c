static const char* dhcp_state_name(int s)
{
    switch (s) {
    case 0: return "OFF";
    case 1: return "REQUESTING";
    case 2: return "INIT";
    case 3: return "REBOOTING";
    case 4: return "REBINDING";
    case 5: return "RENEWING";
    case 6: return "SELECTING";
    case 7: return "INFORMING";
    case 8: return "CHECKING";
    case 9: return "PERMANENT";
    case 10:return "BOUND";
    default:return "UNKNOWN";
    }
}

static void print_net_status(void)
{
    printf("[NET] link=%d up=%d\r\n",
           netif_is_link_up(&gnetif),
           netif_is_up(&gnetif));

    printf("[NET] IP=%s\r\n", ip4addr_ntoa(netif_ip4_addr(&gnetif)));
    printf("[NET] MASK=%s\r\n", ip4addr_ntoa(netif_ip4_netmask(&gnetif)));
    printf("[NET] GW=%s\r\n", ip4addr_ntoa(netif_ip4_gw(&gnetif)));
}

static void print_dhcp_status(void)
{
    struct dhcp *d = netif_dhcp_data(&gnetif);
    int state = d ? d->state : -1;
    printf("[DHCP] supplied=%d state=%d(%s) tries=%d\r\n",
           dhcp_supplied_address(&gnetif) ? 1 : 0,
           state, dhcp_state_name(state),
           d ? d->tries : -1);
}
static int dhcp_start_and_wait(uint32_t timeout_ms)
{
    uint32_t start = sys_now();

    printf("[DHCP] start\r\n");
    dhcp_start(&gnetif);

    while ((sys_now() - start) < timeout_ms)
    {
        print_dhcp_status();
        print_net_status();

        // IP가 할당됐는지 확인
        if (dhcp_supplied_address(&gnetif) &&
            !ip4_addr_isany_val(*netif_ip4_addr(&gnetif)))
        {
            printf("[DHCP] OK\r\n");
            return 0;
        }

        sys_msleep(500);
    }

    printf("[DHCP] TIMEOUT\r\n");
    return -1;
}

